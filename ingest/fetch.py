"""Fetch the policy corpus from rbi.org.in:  python -m ingest fetch

Downloads each page in `ingest/sources.py`, extracts the direction text (not the site chrome), and writes
`data/policies/<slug>.txt` with a provenance header, plus `SOURCES.json` / `SOURCES.md` listing url, title,
fetch date and content hash. It never invents text: what is saved is what the RBI page contains.
"""

from __future__ import annotations

import hashlib
import html as html_lib
import json
import re
import time
import urllib.request
from datetime import UTC, datetime
from html.parser import HTMLParser
from pathlib import Path

from drishti.config import get_settings
from ingest.sources import SOURCES, Source

UA = "Mozilla/5.0 (compatible; drishti-ingest/0.2; research use)"
_BLOCK = {"p", "div", "br", "tr", "li", "h1", "h2", "h3", "h4", "h5", "table", "ul", "ol"}
_START = re.compile(r"^\s*(In exercise of the powers|Chapter I\b|Part A\b|Preamble)", re.I | re.M)
_FOOTER = re.compile(r"^\s*(Web Information Manager|Accessibility Statement|Supports: Google Chrome)", re.I | re.M)


class _Text(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []
        self._skip = 0

    def handle_starttag(self, tag: str, attrs: list) -> None:
        if tag in {"script", "style", "noscript"}:
            self._skip += 1
        if tag in _BLOCK:
            self.parts.append("\n")

    def handle_endtag(self, tag: str) -> None:
        if tag in {"script", "style", "noscript"}:
            self._skip = max(0, self._skip - 1)
        if tag in _BLOCK:
            self.parts.append("\n")

    def handle_data(self, data: str) -> None:
        if not self._skip:
            self.parts.append(data)


def html_to_text(html: str) -> str:
    """Visible text of an RBI direction page, trimmed to the direction body."""
    p = _Text()
    p.feed(html)
    text = "".join(p.parts).replace("\xa0", " ")
    text = re.sub(r"[ \t]+", " ", text)
    lines = [ln.strip() for ln in text.split("\n")]
    text = re.sub(r"\n{2,}", "\n", "\n".join(ln for ln in lines if ln))
    m = _START.search(text)
    if m:
        text = text[m.start():]
    f = _FOOTER.search(text)
    if f:
        text = text[: f.start()]
    return text.strip()


def page_title(html: str) -> str:
    html = html_lib.unescape(html)
    m = re.search(r"(Reserve Bank of India \([^<\n]{10,200}?Directions,?\s*\d{4}[^<\n]{0,60})", re.sub(r"<[^>]+>", "\n", html))
    return re.sub(r"\s+", " ", m.group(1)).strip() if m else ""


def fetch_one(src: Source, out_dir: Path, opener=urllib.request.urlopen) -> dict:  # noqa: ANN001
    req = urllib.request.Request(src.url, headers={"User-Agent": UA})  # noqa: S310 - fixed https RBI URL
    with opener(req, timeout=60) as resp:  # noqa: S310 - fixed https RBI URL
        html = resp.read().decode("utf-8", errors="ignore")
    title = page_title(html)
    if src.expected_title not in html_lib.unescape(html):
        raise ValueError(f"{src.url}: expected title text {src.expected_title!r} not found; the page layout may have changed")
    text = html_to_text(html)
    if len(text) < 5000:
        raise ValueError(f"{src.url}: only {len(text)} characters extracted; refusing to ingest a stub")
    fetched = datetime.now(UTC).strftime("%Y-%m-%d")
    header = (f"# Source: {src.url}\n# Title: {title}\n# Fetched: {fetched}\n# Publisher: Reserve Bank of India\n"
              "# Format: web text (no pagination)\n")
    (out_dir / f"{src.slug}.txt").write_text(header + text + "\n", encoding="utf-8")
    return {"slug": src.slug, "url": src.url, "title": title, "fetched": fetched, "characters": len(text),
            "sha256": hashlib.sha256(text.encode()).hexdigest()[:16], "topics": src.topics}


def write_sources_md(entries: list[dict], out_dir: Path) -> None:
    rows = "\n".join(f"| `{e['slug']}.txt` | {e['title']} | {e['url']} | {e['fetched']} | {e['characters']:,} |" for e in entries)
    (out_dir / "SOURCES.md").write_text(
        "# Policy corpus sources\n\n"
        "Real, public Reserve Bank of India directions. The text is extracted verbatim from the RBI pages below by\n"
        "`python -m ingest fetch` (see `ingest/fetch.py`); nothing here is written or paraphrased by hand or by an LLM.\n"
        "This file is regenerated by the command. Provenance (hashes) is in `SOURCES.json`.\n\n"
        "| File | Title (as printed on the RBI page) | Source | Fetched | Characters |\n|---|---|---|---|---|\n"
        f"{rows}\n\n"
        "Add more documents by saving a `.pdf` or `.txt` into this folder (PDFs from rbidocs.rbi.org.in must be saved "
        "from a browser; the server blocks scripts) and running `make ingest`.\n", encoding="utf-8")


def run(out_dir: Path | None = None, delay: float = 1.0, opener=urllib.request.urlopen) -> list[dict]:  # noqa: ANN001
    out_dir = out_dir or get_settings().policies_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    entries = []
    for i, src in enumerate(SOURCES):
        if i:
            time.sleep(delay)  # be polite to the publisher's server
        entries.append(fetch_one(src, out_dir, opener))
        print(f"fetched {src.slug}: {entries[-1]['characters']:,} characters")
    (out_dir / "SOURCES.json").write_text(json.dumps(entries, indent=2))
    write_sources_md(entries, out_dir)
    return entries


if __name__ == "__main__":
    run()
